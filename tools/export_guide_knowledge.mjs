// מייצא את התוכן של האתר אל "מורה הדרך" של דבר עם ההיסטוריה (history-talk/characters/guide):
//   sources/*.html  — מאגר הידע שהוא מחפש בו בשיחה חופשית (search_sources): צירי הזמן, האישים,
//                     מפת הלמידה, האדריכלות, טבלת התקופות, "מי אני", דפי הידע של הדמויות,
//                     וכל שאלות השאלונים עם התשובה וההסבר.
//   questions.json — מאגר השאלות שהוא שולף ממנו כשבוחנים אותו (quiz_questions): שאלות אמריקאיות
//                     מהשאלונים, שאלות השלמה ממבחני הקורס, ושאלות "איפה זה?" ממפת הלמידה.
// הסדר: מהאתר אל history-talk, ולא להפך — כך כל תוכן חדש באתר נכנס בהרצה הבאה.
//
// הרצה מהשורש: node --import ./tests/register-ts.mjs tools/export_guide_knowledge.mjs
// ואחר כך, ב-history-talk: npm run build:knowledge

import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const OUT = join(ROOT, "history-talk/characters/guide");
const SITE = "https://cfir94.github.io/moreh-derech";
const data = (p) => import(join(ROOT, "src/data", p));
const json = (p) => JSON.parse(readFileSync(join(ROOT, "src/data", p), "utf8"));

const esc = (s) => String(s ?? "").replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const clean = (s) => String(s ?? "").replace(/\s+/g, " ").trim();
/** שורות "תווית: ערך" לפריט, בלי שדות ריקים. */
const lines = (pairs) => pairs.filter(([, v]) => clean(v)).map(([k, v]) => (k ? `${k}: ${clean(v)}` : clean(v)));

// כל פריט מקבל כתובת ייחודית: build-knowledge מצרף קטע קצר לקודמו כשהכתובת שלהם זהה, ואז שאלה אחת
// הייתה נבלעת בתוך קטע של שאלה אחרת ונחתכת בתצוגה.
const used = new Map();
const unique = (url) => {
  const n = (used.get(url) ?? 0) + 1;
  used.set(url, n);
  return n === 1 ? url : `${url}${url.includes("#") ? "-" : "#"}${n}`;
};

/** קובצי המקור של מורה הדרך, לרשימת המקורות ב-character.json. */
const manifest = [];

class Doc {
  parts = [];
  book(title) {
    this.parts.push(`<h2>${esc(title)}</h2>`);
    return this;
  }
  item(title, url, paragraphs) {
    const body = paragraphs.map(clean).filter(Boolean);
    if (!body.length) return this;
    this.parts.push(`<h3 data-anchor="${esc(unique(url))}">${esc(title)}</h3>`, ...body.map((p) => `<p>${esc(p)}</p>`));
    return this;
  }
  write(file, header, url = SITE) {
    manifest.push({ title: header, translator: "אבן דרך למורי דרך", url, license: "חומר הלימוד של האתר", file, refTitle: "" });
    writeFileSync(join(OUT, "sources", file), [`<!-- ${header} — generated by tools/export_guide_knowledge.mjs -->`, ...this.parts].join("\n") + "\n");
    return this.parts.length;
  }
}

rmSync(join(OUT, "sources"), { recursive: true, force: true });
