// ---- דפי הידע של שתים־עשרה הדמויות ----
{
  const dir = join(ROOT, "history-talk/characters");
  const d = new Doc();
  for (const id of readdirSync(dir).sort()) {
    if (id === "guide") continue;
    let sheet;
    try {
      sheet = readFileSync(join(dir, id, "knowledge-sheet.md"), "utf8");
    } catch {
      continue;
    }
    const name = JSON.parse(readFileSync(join(dir, id, "character.json"), "utf8")).nameHe;
    d.book(`${name} — דף הידע של הדמות`);
    // כל כותרת ## היא פרק; שורות טבלה וסימני markdown נשטחים לטקסט.
    for (const section of sheet.split(/^## /m).slice(1)) {
      const [title, ...rest] = section.split("\n");
      const paras = rest
        .map((l) => l.replace(/^\s*[-*>]\s*/, "").replace(/\*\*/g, "").replace(/^\|?\s*-+\s*\|.*$/, "").replace(/\|/g, " · ").trim())
        .filter(Boolean);
      d.item(`${name}: ${title.trim()}`, `${SITE}/timelines/history-talk`, paras);
    }
  }
  counts.characters = d.write("characters.html", "דפי הידע של דמויות ״דבר עם ההיסטוריה״", `${SITE}/timelines/history-talk`);
}

// ---- השאלונים: מקור ידע (שאלה + תשובה + הסבר) וגם מאגר שאלות ----
const { QUIZZES } = await data("quizzes/index.ts");
const { COURSE_EXAMS } = await data("exams/course/index.ts");
const { TOPIC_LABELS } = await data("topics.ts");
const VISUAL = /בתמונה|שבתמונה|בצילום|באיור|במפה ש/;
// אמינות התשובה: מפתח רשמי, פתרון של אפרת נקש (לא רשמי), או תשובה שהוסקה למועד בלי מפתח.
const reliability = (quiz, q) =>
  quiz.slug === "exam-bank" ? "פתרון של אפרת נקש, לא מפתח רשמי" : /לא רשמיות/.test(q.category) ? "תשובה שהוסקה, לא מפתח רשמי" : "";

const questions = [];
const seen = new Set();
for (const quiz of QUIZZES) {
  const d = new Doc().book(quiz.label);
  for (const q of quiz.questions) {
    const correct = q.answers.findIndex((a) => a.correct);
    if (correct < 0 || q.answers.length < 2) continue;
    const key = clean(q.question).replace(/[^\p{L}\p{N}]/gu, "") + "|" + clean(q.answers[correct].text);
    const dup = seen.has(key);
    seen.add(key);
    const note = reliability(quiz, q);
    const topic = q.topic ? TOPIC_LABELS[q.topic] : "";
    d.item(q.category, `${SITE}/quizzes/${quiz.slug}`, [
      `שאלה: ${q.question}`,
      `התשובה: ${q.answers[correct].text}${note ? ` (${note})` : ""}`,
      ...lines([["הסבר", q.explanation], ["מקור", q.source]]),
    ]);
    if (dup) continue; // אותה שאלה מופיעה גם במועד וגם במאגר — פעם אחת מספיקה בבוחן
    if (q.image || VISUAL.test(q.question)) continue; // בשיחה קולית אין תמונה
    questions.push({
      id: `${quiz.slug}:${q.id}`,
      quiz: quiz.label,
      category: q.category,
      topic,
      question: clean(q.question),
      options: q.answers.map((a) => clean(a.text)),
      correct,
      explanation: clean(q.explanation),
      ...(note ? { note } : {}),
      url: `${SITE}/quizzes/${quiz.slug}`,
    });
  }
  counts[`quiz:${quiz.slug}`] = d.write(`quiz-${quiz.slug}.html`, `שאלון: ${quiz.label}`, `${SITE}/quizzes/${quiz.slug}`);
}

// שאלות השלמה ממבחני הקורס (תשובה פתוחה, "/" מפריד בין נוסחים קבילים).
for (const exam of COURSE_EXAMS) {
  for (const q of exam.questions) {
    if (q.kind !== "fill" || !q.answerText) continue;
    // הכותרת: "מבחן בית שני–ביזנטית 2 — נחמיה, בר כוכבא והתיאטרון הרומי"; הקטגוריה היא מה שאחרי המקף —
    // "subjects" רחב מדי (כל נושאי הבלוק) ומושך כל שאלה של הבלוק לכל חיפוש.
    const [title, sub = ""] = exam.label.he.split(" — ");
    questions.push({
      id: `${exam.slug}:${q.number}`,
      quiz: title,
      category: sub,
      topic: q.topic ? TOPIC_LABELS[q.topic] : "",
      question: clean(q.question.he || q.statement.he),
      answer: clean(q.answerText),
      explanation: clean(q.explanation),
      url: `${SITE}/exams/${exam.slug}`,
    });
  }
}

// "איפה זה?" ממפת הלמידה — התשובה היא שם האתר.
{
  const lm = await data("learning-map/index.ts");
  for (const s of lm.SITES) {
    for (const [i, ask] of (s.ask ?? []).entries()) {
      questions.push({
        id: `map:${s.id}:${i}`,
        quiz: "מפת הלמידה",
        category: lm.PERIOD_BY_ID[s.layers[0]?.period]?.title ?? "",
        topic: "",
        question: clean(ask),
        answer: s.name,
        explanation: clean(s.tip || s.about),
        url: `${SITE}/map/learn/#${s.id}`,
      });
    }
  }
}

// "מי אני?" — שאלות פתוחות על אישים. אישי רומא: התפקיד והמעשה, והתשובה היא השם.
{
  const rp = await data("roman-people.ts");
  const era = Object.fromEntries(rp.ERAS.map((e) => [e.id, e.label]));
  for (const p of rp.ROMAN_PEOPLE) {
    const role = p.roles.map((r) => rp.ROLES[r]?.label).filter(Boolean).join(", ");
    questions.push({
      id: `roman-people:${p.id}`,
      quiz: "אישי רומא ויהודה",
      category: [era[p.era], role].filter(Boolean).join(" · "),
      topic: "",
      question: clean(`מי אני? ${p.role}, ${p.date}. ${p.action}`).replaceAll(p.name, "____"),
      answer: p.name,
      explanation: clean([p.memory, p.trap].filter(Boolean).join(" ")),
      url: `${SITE}/timelines/roman-people/`,
    });
  }
  // משחק "מי אני": הרמזים כתובים בגוף ראשון ואינם מזכירים את השם.
  for (const p of json("who-am-i/people.json")) {
    questions.push({
      id: `who-am-i:${p.id}`,
      quiz: "מי אני?",
      category: clean(`${p.role} · ${p.date}`),
      topic: "",
      question: clean(`מי אני? ${p.clues.join(" ")}`),
      answer: [p.name, ...(p.aliases ?? [])].join(" / "),
      explanation: clean(p.distinction),
      url: `${SITE}/games/who-am-i`,
    });
  }
}

writeFileSync(join(OUT, "questions.json"), JSON.stringify({ version: 1, questions }) + "\n");

