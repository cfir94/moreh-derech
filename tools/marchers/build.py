"""Write src/components/trail/marcherArt.ts from figures.py.  Run: python3 tools/marchers/build.py
To look at the figures large while drawing: python3 tools/marchers/build.py --view  (writes view.html here)"""
import json, os, sys
here = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, here)
from figures import FIGS
art = {n: dict(zip(("body", "a", "b"), fn())) for n, fn in FIGS.items()}
out = ['/* generated by tools/marchers/build.py from figures.py; do not edit by hand */',
       'export type Stroke = { d: string; w?: number; f?: string; fo?: number; s?: string; o?: number };',
       'export type Art = { body: Stroke[]; a: Stroke[]; b: Stroke[] };', '',
       'export const ART: Record<"assyrian" | "roman" | "priest", Art> = {']
for n, d in art.items():
    out.append(f'  {n}: {json.dumps(d, ensure_ascii=False, separators=(",", ":"))},')
out.append('};')
open(os.path.join(here, '../../src/components/trail/marcherArt.ts'), 'w').write('\n'.join(out) + '\n')
if '--view' in sys.argv:
    C = {"paint": "#fbf6e6", "stone": "#dcc692", "red": "#b5382a", "orange": "#b5651d", "blue": "#2a5a8c", "sign": "#6b4423",
         "skin": "#d9a679", "dark": "#231a10", "gold": "#87560f"}
    CD = dict(C, paint="#46382a", stone="#a88f62", red="#e06049", orange="#e6964c", blue="#8ab6e0", sign="#7d512b", gold="#e8b878")
    def svg(d, fr, h, dark=False):
        cc = CD if dark else C
        def paths(L):
            s = ''
            for p in L:
                s += f'<path d="{p["d"]}" stroke-width="{p.get("w", 1.8)}" fill="{cc[p["f"]] if p.get("f") else "none"}"'
                if "fo" in p: s += f' fill-opacity="{p["fo"]}"'
                if p.get("s"): s += f' stroke="{cc[p["s"]]}"'
                if p.get("w", 1.8) == 0: s += ' stroke="none"'
                if "o" in p: s += f' opacity="{p["o"]}"'
                s += '/>'
            return s
        return (f'<svg viewBox="6 0 54 64" height="{h}" style="color:{"#f5e8c9" if dark else "#2c2014"}" fill="none" stroke="currentColor" '
                f'stroke-linecap="round" stroke-linejoin="round"><g filter="url(#ink64)">{paths(d[fr])}{paths(d["body"])}</g></svg>')
    html = ('<html><body style="margin:0;background:#ead8a8;padding:10px"><svg width="0" height="0" style="position:absolute"><filter id="ink64" x="-10%" y="-10%" width="120%" height="120%">'
            '<feTurbulence type="fractalNoise" baseFrequency="0.55" numOctaves="2" seed="5"/><feDisplacementMap in="SourceGraphic" scale="1.3" xChannelSelector="R" yChannelSelector="G"/></filter></svg>')
    html += '<div style="display:flex;gap:6px">' + ''.join(svg(d, "a", 420) + svg(d, "b", 420) for d in art.values()) + '</div>'
    html += '<div style="display:flex;gap:30px;align-items:end;padding:10px">' + ''.join(svg(d, "a", 120) for d in art.values())
    html += '<div style="background:#382c1e;padding:8px;display:flex;gap:20px">' + ''.join(svg(d, "a", 120, True) for d in art.values()) + '</div></div>'
    open(os.path.join(here, 'view.html'), 'w').write(html + '</body></html>')
print("wrote marcherArt.ts")
