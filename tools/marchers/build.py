"""Draw the marching figures and write src/components/trail/marcherArt.ts.

Each figure is hand-placed paths (assyrian.py, roman.py, priest.py) on a 120x180 sheet.
Run from anywhere:  python3 tools/marchers/build.py
To look at them large while drawing:  python3 render.py assyrian roman priest  (writes view.html)
"""
import json, os, runpy
here = os.path.dirname(os.path.abspath(__file__)); os.chdir(here)
names = ("assyrian", "roman", "priest")
for n in names:
    runpy.run_path(f"{n}.py", run_name="__main__")
out = ['/* generated by tools/marchers/build.py (hand-placed paths); do not edit by hand */',
       'export type Stroke = { d: string; w: number; fill?: 1 };', 'export type Wash = { d: string; c: string };',
       'export type Art = { ink: Stroke[]; wash: Wash[]; a: Stroke[]; b: Stroke[]; washA?: Wash[]; washB?: Wash[] };', '',
       'export const ART: Record<"assyrian" | "roman" | "priest", Art> = {']
for n in names:
    D = json.load(open(f"{n}.json")); os.remove(f"{n}.json")
    out.append(f'  {n}: {json.dumps(D, ensure_ascii=False, separators=(",", ":"))},')
out.append('};')
open(os.path.join(here, '../../src/components/trail/marcherArt.ts'), 'w').write('\n'.join(out) + '\n')
print("wrote marcherArt.ts")
