"""Build the portrait registry only from reviewed image selections and labels."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
candidates = json.loads((root / 'docs/roman-portrait-candidates.json').read_text(encoding='utf-8'))
labels = json.loads((root / 'tools/roman-portrait-labels.json').read_text(encoding='utf-8'))
portraits = {}
for person, label in labels.items():
    candidate = candidates[person]
    assert candidate['status'] == 'downloaded-for-review', person
    portraits[person] = {key: candidate[key] for key in ['file', 'localSrc', 'sourceUrl', 'credit', 'license', 'licenseUrl']}
    portraits[person].update(label)
    portraits[person]['licenseUrl'] = portraits[person]['licenseUrl'].replace('http://creativecommons.org/', 'https://creativecommons.org/')
text = '// Generated by tools/build-roman-portrait-data.py from reviewed selections.\n'
text += 'import type { Portrait } from "./roman-people";\n\n'
text += 'export const LOCAL_PORTRAITS: Record<string, Portrait> = ' + json.dumps(portraits, ensure_ascii=False, indent=2) + ';\n'
(root / 'src/data/roman-portraits.ts').write_text(text, encoding='utf-8')
print('Built', len(portraits), 'local portrait records')
