#!/usr/bin/env python3
"""Fetch the field photos for the classical architecture studio from Wikimedia Commons.

Reads tools/architecture_photos.json — a list of {id, file, chapter, caption,
alt} — asks Commons for each file's author, license and a 1280px rendition
(one batched API request), saves a re-encoded JPEG to
public/architecture/photos/<id>.jpg and writes
src/data/classical-architecture/photos.ts with the attribution every
CC licence asks for.

The photos are hosted on the site itself. upload.wikimedia.org throttles some
networks hard (it refused this repo's build containers outright), so the
.github/workflows/fetch-architecture-photos.yml workflow runs this script on
GitHub's runners whenever the manifest changes and commits the result.

  python3 tools/fetch_architecture_photos.py            # fetch what is missing
  python3 tools/fetch_architecture_photos.py --refresh  # re-download everything
"""
import html
import io
import json
import re
import subprocess
import sys
import time
import urllib.parse
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "tools" / "architecture_photos.json"
OUT_DIR = ROOT / "public" / "architecture" / "photos"
DATA = ROOT / "src" / "data" / "classical-architecture" / "photos.ts"
UA = "MorehDerechStudyBot/1.0 (https://cfir94.github.io/moreh-derech/; educational)"
ALLOWED = re.compile(r"^(CC0|Public domain|CC BY(-SA)? [\d.]+( [a-z]+)?|Attribution|No restrictions|PD.*)$", re.I)


def curl(url: str) -> bytes:
    """GET with the polite User-Agent Wikimedia asks for, backing off on 429."""
    for attempt in range(10):
        proc = subprocess.run(["curl", "-s", "-m", "90", "-A", UA, "-w", "\n%{http_code}", url], capture_output=True)
        body, _, code = proc.stdout.rpartition(b"\n")
        if code == b"200":
            return body
        print(f"  HTTP {code.decode()} — retrying", flush=True)
        time.sleep(10 * (attempt + 1))
    raise SystemExit(f"HTTP {code.decode()} for {url}")


def plain(value: str) -> str:
    return re.sub(r"\s+", " ", html.unescape(re.sub(r"<[^>]+>", "", value or ""))).strip()


def main() -> None:
    refresh = "--refresh" in sys.argv
    items = json.loads(MANIFEST.read_text(encoding="utf-8"))
    titles = [f"File:{item['file']}" for item in items]
    info: dict[str, dict] = {}
    for start in range(0, len(titles), 40):
        params = {
            "action": "query", "format": "json", "prop": "imageinfo", "titles": "|".join(titles[start:start + 40]),
            "iiprop": "url|size|extmetadata", "iiurlwidth": 1280,
            "iiextmetadatafilter": "Artist|LicenseShortName|LicenseUrl|Credit",
        }
        data = json.loads(curl("https://commons.wikimedia.org/w/api.php?" + urllib.parse.urlencode(params)))
        normalized = {n["to"]: n["from"] for n in data["query"].get("normalized", [])}
        for page in data["query"]["pages"].values():
            if "imageinfo" not in page:
                raise SystemExit(f"missing on Commons: {page['title']}")
            info[normalized.get(page["title"], page["title"])] = page["imageinfo"][0]
        time.sleep(3)

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    rows = []
    for item in items:
        meta = info[f"File:{item['file']}"]
        ext = meta.get("extmetadata", {})
        license_name = plain(ext.get("LicenseShortName", {}).get("value", ""))
        if not ALLOWED.match(license_name):
            raise SystemExit(f"{item['id']}: licence '{license_name}' is not one we can reuse")
        target = OUT_DIR / f"{item['id']}.jpg"
        if refresh or not target.exists():
            image = Image.open(io.BytesIO(curl(meta.get("thumburl", meta["url"])))).convert("RGB")
            image.thumbnail((1280, 1280))
            image.save(target, "JPEG", quality=80, optimize=True, progressive=True)
            time.sleep(3)
        width, height = Image.open(target).size
        rows.append({
            "id": item["id"], "chapter": item["chapter"], "caption": item["caption"], "alt": item["alt"],
            "src": f"/architecture/photos/{item['id']}.jpg", "width": width, "height": height,
            "author": plain(ext.get("Artist", {}).get("value", "")) or "לא צוין",
            "license": license_name, "licenseUrl": plain(ext.get("LicenseUrl", {}).get("value", "")),
            "source": meta["descriptionurl"],
        })
        print(f"{item['id']:28} {width}x{height}  {license_name}", flush=True)

    DATA.write_text(
        "// Generated by tools/fetch_architecture_photos.py from tools/architecture_photos.json — do not edit by hand.\n"
        "export type ArchPhoto = { id: string; chapter: string; caption: string; alt: string; src: string; width: number; height: number; author: string; license: string; licenseUrl: string; source: string };\n\n"
        f"export const ARCH_PHOTOS: ArchPhoto[] = {json.dumps(rows, ensure_ascii=False, indent=2)};\n",
        encoding="utf-8",
    )
    print(f"wrote {len(rows)} photos")


if __name__ == "__main__":
    main()
