#!/usr/bin/env python3
"""Downloads the Geological Survey of Israel's geological map of Israel,
1:200,000 (2014 edition), for the geology aid's "official" layer (LA-72).

Source: the GSI's public ArcGIS feature service
  egozi.gsi.gov.il/arcgis/rest/services/Hosted/Israel_200000_2014_geology/FeatureServer/5
(layer "GeoFormations": 8,450 polygons, 109 formations). Credit: המכון הגאולוגי לישראל.

The geometry is simplified on the server (maxAllowableOffset) to what a
country-wide 3D overview can show, and the official colours are read from the
layer's own renderer, so the map looks like the printed one.

Writes:
  public/geology/gsi-200k.geojson   polygons with a single property "c" (formation code)
  src/data/geology/gsi-units.ts     generated: code -> symbol, Hebrew and English name, colour

    python3 tools/fetch_gsi_geology.py
"""
from __future__ import annotations

import json
import subprocess
import sys
import urllib.parse
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LAYER = "https://egozi.gsi.gov.il/arcgis/rest/services/Hosted/Israel_200000_2014_geology/FeatureServer/5"
OUT_GEO = ROOT / "public/geology/gsi-200k.geojson"
OUT_TS = ROOT / "src/data/geology/gsi-units.ts"
OFFSET = 0.0015   # degrees (~150 m): about one pixel of the 3D texture
PAGE = 1000


def get(url: str) -> dict:
    out = subprocess.run(["curl", "-s", "-m", "120", url], capture_output=True, check=True).stdout
    data = json.loads(out)
    if "error" in data:
        raise RuntimeError(data["error"])
    return data


def main() -> None:
    meta = get(f"{LAYER}?f=json")
    renderer = meta["drawingInfo"]["renderer"]
    colours = {}
    for info in renderer["uniqueValueInfos"]:
        r, g, b, _ = info["symbol"]["color"]
        colours[int(info["value"])] = f"#{r:02X}{g:02X}{b:02X}"

    features, units, offset = [], {}, 0
    while True:
        q = urllib.parse.urlencode({
            "where": "1=1", "outFields": "code,symbol,name_heb,name_eng", "outSR": 4326,
            "maxAllowableOffset": OFFSET, "geometryPrecision": 4, "resultOffset": offset,
            "resultRecordCount": PAGE, "orderByFields": "fid", "f": "geojson",
        })
        page = get(f"{LAYER}/query?{q}")
        batch = page.get("features", [])
        for f in batch:
            p = f["properties"]
            code = int(p["code"])
            units.setdefault(code, {"symbol": p["symbol"], "he": p["name_heb"], "en": p["name_eng"]})
            if f.get("geometry"):
                features.append({"type": "Feature", "properties": {"c": code}, "geometry": f["geometry"]})
        print(f"{offset + len(batch)} polygons", file=sys.stderr)
        if len(batch) < PAGE:
            break
        offset += PAGE

    OUT_GEO.parent.mkdir(parents=True, exist_ok=True)
    OUT_GEO.write_text(json.dumps({"type": "FeatureCollection", "features": features}, separators=(",", ":")), encoding="utf-8")

    rows = []
    for code in sorted(units):
        u = units[code]
        rows.append(f"  {code}: {{ symbol: {json.dumps(u['symbol'].strip())}, he: {json.dumps((u['he'] or '').strip(), ensure_ascii=False)}, "
                    f"en: {json.dumps((u['en'] or '').strip())}, color: \"{colours.get(code, '#CCCCCC')}\" }},")
    OUT_TS.write_text(
        "// Generated by tools/fetch_gsi_geology.py — do not edit by hand.\n"
        "// המפה הגאולוגית של ישראל 1:200,000 (2014), המכון הגאולוגי לישראל. הצבעים הרשמיים של המפה.\n"
        "export type GsiUnit = { symbol: string; he: string; en: string; color: string };\n"
        "export const GSI_UNITS: Record<number, GsiUnit> = {\n" + "\n".join(rows) + "\n};\n",
        encoding="utf-8",
    )
    print(f"{len(features)} polygons, {len(units)} units, {OUT_GEO.stat().st_size // 1024} KB")


if __name__ == "__main__":
    main()
