"""
Build the bank of real licensing-exam questions, by syllabus topic, with our own answers.

Input:
* tools/exam_bank/items.json — 2,634 multiple-choice items from the Ministry of Tourism's
  licensing papers, 2000–2017: id, question and the four options as printed. The ids are the
  ones the old bank used, so users' progress carries over.
* tools/exam_bank/keys/NN.txt — our answer for each item (docs/team/codex/EB.md):
  "<id> <0-3|x> <h|m|l>". h = sure, m = probable, l = a guess or a question that depends on
  its year, x = unanswerable.

What goes in:
* h — as is.
* m — with a note after answering that the answer is ours and probable, to check against the
  material.
* l and x — left out. A guessed answer before a licensing exam is worse than none.

The topic of each question is ours too: tools/topics.py (keywords, with the hand-checked
tools/topic_overrides.txt winning).

    python3 tools/import_exam_bank.py
"""

import json
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from topics import LABELS, TOPICS, topic_of  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
ITEMS = ROOT / "tools/exam_bank/items.json"
KEYS = ROOT / "tools/exam_bank/keys"
OUT = ROOT / "src/data/quizzes/exam-bank.ts"

HEADER = """// Auto-generated by tools/import_exam_bank.py — do not edit by hand.
//
// Real multiple-choice items from the Ministry of Tourism's licensing papers, 2000–2017,
// quoted as printed. The answers and the topics are ours (tools/exam_bank/keys); they are
// not an official key, and the quiz says so on screen.
import type { Quiz } from "@/data/quizzes/types";

const quiz: Quiz = """

PROBABLE = "התשובה המסומנת היא שלנו, והיא סבירה אבל לא ודאית. כדאי לאמת אותה מול החומר."


def read_keys():
    keys = {}
    for f in sorted(KEYS.glob("*.txt")):
        for line in f.read_text().splitlines():
            line = line.split("#")[0].strip()
            if not line:
                continue
            qid, ans, conf = line.split()
            keys[int(qid)] = (ans, conf)
    return keys


def main():
    items = json.loads(ITEMS.read_text())
    keys = read_keys()
    missing = [i["id"] for i in items if i["id"] not in keys]
    if missing:
        raise SystemExit(f"{len(missing)} items have no answer yet, e.g. {missing[:5]}")

    questions, left_out = [], Counter()
    for item in items:
        ans, conf = keys[item["id"]]
        if ans == "x" or conf == "l":
            left_out[conf if ans != "x" else "x"] += 1
            continue
        options = item["options"]
        q = {
            "id": item["id"],
            "question": item["question"],
            "category": "",
            "topic": topic_of(item["id"], item["question"], options),
            "source": "מבחני הרישוי של משרד התיירות, 2000–2017",
            "answers": [{"text": o, "correct": i == int(ans)} for i, o in enumerate(options)],
        }
        q["category"] = LABELS[q["topic"]]
        if conf == "m":
            q["explanation"] = PROBABLE
        questions.append(q)

    # syllabus order, then the id, so a re-run gives the same file
    order = {k: n for n, (k, _, _) in enumerate(TOPICS)}
    questions.sort(key=lambda q: (order[q["topic"]], q["id"]))

    quiz = {
        "slug": "exam-bank",
        "label": "מאגר מבחני הרישוי לפי נושא",
        "notice": (
            "השאלות לקוחות כלשונן ממבחני הרישוי של משרד התיירות (2000–2017). התשובות נקבעו על "
            "ידינו ואינן מפתח רשמי. שאלות שלא היינו בטוחים בתשובתן הוצאו, וליד תשובה סבירה אך "
            "לא ודאית מופיעה הערה."
        ),
        "categoryNoun": {"one": "נושא", "many": "נושאים"},
        "categories": [label for k, label, _ in TOPICS if any(q["topic"] == k for q in questions)],
        "questions": questions,
    }
    OUT.write_text(HEADER + json.dumps(quiz, ensure_ascii=False, indent=2) + ";\n\nexport default quiz;\n")

    confs = Counter(keys[q["id"]][1] for q in questions)
    print(f"{len(questions)} questions ({confs['h']} sure, {confs['m']} probable); left out: {dict(left_out)}")
    for label in quiz["categories"]:
        print(f"   {label:28s} {sum(1 for q in questions if q['category'] == label):4d}")


if __name__ == "__main__":
    main()
