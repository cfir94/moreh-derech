// מחלץ את הנתונים של אפליקציית History_timeline המוטמעת (public/embeds/history-timeline/index.html)
// לקובצי TypeScript, כדי שיהיו בריפו כנתונים: מלכי ישראל ויהודה, הנביאים ואבני הדרך, שרשרת הספרים
// של היהדות, וממצאי תקופת הברזל. זה שלב ראשון של LA-40 (בניית העמודים מחדש באתר): בינתיים הנתונים
// משמשים את מאגר הידע של מוטי. הקבצים ב-src/data/history-timeline/ הם generated — לא לערוך ידנית.
//
// הרצה מהשורש: node tools/extract_history_timeline.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const html = readFileSync(join(ROOT, "public/embeds/history-timeline/index.html"), "utf8");

/** The literal assigned to `const NAME = …`, evaluated as data (the literals hold no code). */
function literal(name) {
  const start = html.search(new RegExp(`const ${name} ?= ?[\\[{]`));
  if (start < 0) throw new Error(`${name}: not found`);
  let i = html.indexOf("=", start) + 1;
  while (/\s/.test(html[i])) i++;
  let depth = 0, j = i, quote = null, escaped = false;
  for (; j < html.length; j++) {
    const c = html[j];
    if (quote) { if (escaped) escaped = false; else if (c === "\\") escaped = true; else if (c === quote) quote = null; continue; }
    if (c === '"' || c === "'" || c === "`") { quote = c; continue; }
    if (c === "[" || c === "{") depth++;
    else if ((c === "]" || c === "}") && --depth === 0) break;
  }
  return vm.runInNewContext(`(${html.slice(i, j + 1)})`, {});
}

const header = (what) => `/* ${what}. Generated by tools/extract_history_timeline.mjs from public/embeds/history-timeline/index.html — do not edit by hand. */\n`;
const write = (file, body) => writeFileSync(join(ROOT, "src/data/history-timeline", file), body);
const json = (value) => JSON.stringify(value, null, 2);

const kings = literal("KINGS_GANTT");
const prophets = literal("PROPHETS");
const milestones = literal("MILESTONES");
write("kings.ts", header("מלכי ישראל ויהודה, הנביאים ואבני הדרך") + `
export type King = { name: string; start: number; end: number; prophet?: string; important?: boolean; note?: string; /** Layout hint of the original chart (a second lane for overlapping reigns). */ row?: number };
export type Prophet = { kingdom: string; era: string; known: string };
export type Milestone = { year: number; title: string; desc: string };

/** ${kings.source}. השנים לפנה״ס. */
export const KINGS_SOURCE = ${json(kings.source)};
export const UNITED_KINGS: King[] = ${json(kings.united)};
export const JUDAH_KINGS: King[] = ${json(kings.judah)};
export const ISRAEL_KINGS: King[] = ${json(kings.israel)};
export const PROPHETS: Record<string, Prophet> = ${json(prophets)};
export const KINGDOM_MILESTONES: Milestone[] = ${json(milestones)};
`);

const judaism = literal("JUDAISM");
const eras = Object.fromEntries(Object.entries(judaism.eras).map(([id, era]) => [id, { label: era.label, range: era.range }]));
write("judaism.ts", header("שרשרת הספרים של היהדות, מרכזי התורה והיסודות") + `
export type JudaismEra = { label: string; range: string };
export type JudaismBook = { year: number; yearLabel: string; era: string; important: boolean; title: string; short: string; author?: string; when?: string; where?: string; role?: string; [key: string]: unknown };
export type TorahCenter = { place: string; when: string; what: string };
export type Foundation = { q: string; a: string; note?: string };

export const JUDAISM_ERAS: Record<string, JudaismEra> = ${json(eras)};
export const JUDAISM_CHAIN: JudaismBook[] = ${json(judaism.chain)};
export const TORAH_CENTERS: TorahCenter[] = ${json(judaism.centers)};
export const JUDAISM_FOUNDATIONS: Foundation[] = ${json(judaism.foundations)};
`);

const archaeology = literal("ARCHAEOLOGY");
const kinds = Object.fromEntries(Object.entries(archaeology.kinds).map(([id, kind]) => [id, kind.label]));
write("finds.ts", header("אירועים וממצאים של תקופת הברזל (מסעות, מצורים, כתובות וביצורים)") + `
export type IronFind = { year: number; yearLabel: string; kind: string; chart?: boolean; title: string; short: string; desc: string; where?: string; image?: { file: string; caption: string; credit: string; license: string; [key: string]: unknown } };

export const FIND_KINDS: Record<string, string> = ${json(kinds)};
export const IRON_FINDS: IronFind[] = ${json(archaeology.items)};
`);

console.log(`kings: ${kings.united.length}+${kings.judah.length}+${kings.israel.length}, prophets: ${Object.keys(prophets).length}, milestones: ${milestones.length}, books: ${judaism.chain.length}, centers: ${judaism.centers.length}, foundations: ${judaism.foundations.length}, finds: ${archaeology.items.length}`);
