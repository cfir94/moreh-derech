#!/usr/bin/env python3
"""Builds the relief of the geology aid's 3D map (/timelines/geology).

From the elevation tiles the route map already ships
(public/embeds/map/data/terrain, terrarium, zoom 11) it writes:

  public/geology/relief.bin           Int16 little-endian, metres, row by row
                                      from north to south (GRID_W x grid_h)
  public/geology/water-light.png      sea and lakes, transparent over land,
  public/geology/water-dark.png       drawn over the geology on the texture
  src/data/geology/relief.ts          generated — the frame (Web Mercator) and
                                      the grid size, so the page projects the
                                      geology polygons exactly onto the relief

The geology itself is not rasterised here: the page reads the same GeoJSON as
the route map (public/embeds/map/js/data/geology_*.geojson) and paints it on a
canvas, so the two maps cannot drift apart.

    python3 tools/build_geology_relief.py
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw

sys.path.insert(0, str(Path(__file__).resolve().parent))
from build_learning_map_base import (  # noqa: E402
    GEO, blur, load_dem, ring_to_raster, sheet_frame,
)
import json  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "public/geology"
OUT_TS = ROOT / "src/data/geology/relief.ts"

BOUNDS = (34.2, 29.45, 35.95, 33.35)   # lon0, lat0, lon1, lat1
GRID_W = 256                           # vertices across; plenty for a 3D overview
WATER_W = 1024                         # texture pixels across

THEMES = {"light": ("#9cc7d6", "#86b9cc"), "dark": ("#1d4560", "#24577a")}  # sea, lake


def hex_rgb(c: str):
    return tuple(int(c[i:i + 2], 16) for i in (1, 3, 5))


def sea_mask(dem: np.ndarray) -> np.ndarray:
    """The Mediterranean and the Gulf of Eilat (same rule as the learning map):
    below 0 m, but only on the coastal side, because the rift is below 0 m too."""
    h, w = dem.shape
    lon0, lat0, lon1, lat1 = BOUNDS
    lons = np.linspace(lon0, lon1, w)[None, :].repeat(h, 0)
    lats = np.linspace(lat1, lat0, h)[:, None].repeat(w, 1)
    coastal = (lons < 35.25) & ((lats > 31.2) | (lons < 34.6))
    coastal |= (lats < 29.56) & (lons > 34.8) & (lons < 35.1)
    return blur(np.where(coastal, dem, np.maximum(dem, 50.0)), 1.2) < 0.5


def main() -> None:
    frame = sheet_frame({"bounds": BOUNDS, "width": 1000})
    dem = load_dem(frame, GRID_W).copy()
    h = dem.shape[0]
    # the sea is drawn flat: the tiles carry the sea floor, which would turn
    # the Mediterranean into a pit next to the coast
    dem[sea_mask(dem)] = -5
    OUT.mkdir(parents=True, exist_ok=True)
    np.clip(np.round(dem), -32768, 32767).astype("<i2").tofile(OUT / "relief.bin")

    # water mask at texture resolution (same rule as the learning map)
    big = load_dem(frame, WATER_W)
    wh, ww = big.shape
    sea = sea_mask(big)

    ne = json.loads((GEO / "natural-earth.json").read_text())
    px = ww / frame["w"]
    lake_img = Image.new("L", (ww, wh), 0)
    draw = ImageDraw.Draw(lake_img)
    for lake in ne["lakes"]:
        draw.polygon(ring_to_raster(frame, lake["ring"], px), fill=255)
    lake = np.asarray(lake_img) > 0

    for theme, (sea_c, lake_c) in THEMES.items():
        rgba = np.zeros((wh, ww, 4), dtype=np.uint8)
        rgba[sea] = (*hex_rgb(sea_c), 255)
        rgba[lake] = (*hex_rgb(lake_c), 255)
        Image.fromarray(rgba, "RGBA").save(OUT / f"water-{theme}.png", optimize=True)

    OUT_TS.parent.mkdir(parents=True, exist_ok=True)
    OUT_TS.write_text(
        "// Generated by tools/build_geology_relief.py — do not edit by hand.\n"
        "export const RELIEF = {\n"
        f"  bounds: [{', '.join(str(b) for b in BOUNDS)}] as const,\n"
        f"  frame: {{ x0: {frame['x0']!r}, y0: {frame['y0']!r}, scale: {frame['scale']!r}, w: {frame['w']}, h: {frame['h']} }},\n"
        f"  grid: {{ w: {GRID_W}, h: {h} }},\n"
        f"  water: {{ w: {ww}, h: {wh} }},\n"
        f"  minElevation: {int(dem.min())},\n"
        f"  maxElevation: {int(dem.max())},\n"
        "};\n",
        encoding="utf-8",
    )
    print(f"relief {GRID_W}x{h}, {int(dem.min())}..{int(dem.max())} m; water {ww}x{wh}")


if __name__ == "__main__":
    main()
