"""Turn a summary written in Markdown (content/summaries/<key>.md, the shape in docs/team/gemini/SUM-GEMINI.md)
into src/data/summaries/<key>.ts.

    python3 tools/md_to_summary.py judaism

The Markdown is the reviewed source: fix facts there, then run this again.
"""
import json, re, sys, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
key = sys.argv[1]
md = open(os.path.join(ROOT, f"content/summaries/{key}.md"), encoding="utf8").read()

def clean(t):
    return re.sub(r"\*\*(.+?)\*\*", r"\1", t).strip()

title = re.search(r"^# (.+)$", md, re.M).group(1).strip()
lede = " ".join(l[1:].strip() for l in md.splitlines() if l.startswith(">"))
parts = re.split(r"^## ", md, flags=re.M)[1:]
sections, terms, sites = [], [], []
for part in parts:
    head, _, body = part.partition("\n")
    head = head.strip()
    lines = body.strip().splitlines()
    if head == "מושגים":
        for l in lines:
            m = re.match(r"- \*\*(.+?):\*\*\s*(.+)", l)
            if m: terms.append({"term": m.group(1).strip(), "def": clean(m.group(2))})
        continue
    if head.startswith("איפה פוגשים"):
        for l in lines:
            if l.startswith("- "):
                sites.append(re.sub(r"\s+", " ", clean(l[2:]).replace(" —", " —")))
        continue
    paras, remember, table, buf, mode = [], [], None, [], "body"
    for l in lines + [""]:
        if l.startswith("**לזכור למבחן"):
            mode = "remember"; continue
        if l.startswith("|"):
            cells = [c.strip() for c in l.strip().strip("|").split("|")]
            if all(re.fullmatch(r":?-+:?", c) for c in cells): continue
            if table is None: table = {"head": cells, "rows": []}
            else: table["rows"].append(cells)
            continue
        if mode == "remember":
            if l.startswith("- "): remember.append(clean(l[2:]))
            continue
        if l.strip(): buf.append(l.strip())
        elif buf:
            paras.append(clean(" ".join(buf))); buf = []
    sec = {"title": head, "body": paras, "remember": remember}
    if table: sec["table"] = table
    sections.append(sec)

out = {"key": key, "title": title, "lede": clean(lede), "sections": sections, "terms": terms, "sites": sites}
ts = 'import type { Summary } from "./types";\n\n// generated by tools/md_to_summary.py from content/summaries/' + key + '.md: edit the Markdown, not this file\nconst summary: Summary = ' + json.dumps(out, ensure_ascii=False, indent=2) + ";\n\nexport default summary;\n"
open(os.path.join(ROOT, f"src/data/summaries/{key}.ts"), "w", encoding="utf8").write(ts)
print(f"{key}: {len(sections)} sections, {len(terms)} terms, {len(sites)} sites, {sum(len(x['body']) for x in sections)} paragraphs, {sum(1 for x in sections if 'table' in x)} tables")
