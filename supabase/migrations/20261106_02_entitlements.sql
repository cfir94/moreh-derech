-- B-01: זכאות (ניסיון / מנוי) לאתר מורי דרך.
-- עקרונות:
--   * משתמש קורא רק את השורה שלו. אין לו שום הרשאת כתיבה: מנוי נכתב רק ע"י השרת (md-api, service_role)
--     אחרי התראה מאומתת מחברת הסליקה.
--   * שבוע ניסיון נפתח פעם אחת לכל משתמש, דרך md_start_trial() (security definer, אידמפוטנטי).
--   * הקידומת md_ מפרידה מטבלאות המשחק "אבן דרך", שחולק את אותו פרויקט Supabase.
-- להרצה: Supabase ← SQL Editor ← Run. אידמפוטנטי.

create table if not exists public.md_entitlements (
  user_id uuid primary key references auth.users(id) on delete cascade,
  plan text not null default 'trial'
    check (plan in ('trial', 'monthly', 'yearly', 'founder', 'comp')),
  status text not null default 'active'
    check (status in ('active', 'past_due', 'canceled', 'expired')),
  trial_ends_at timestamptz,
  current_period_end timestamptz,
  cancel_at_period_end boolean not null default false,
  provider text,
  provider_customer_ref text,
  provider_subscription_ref text,
  terms_accepted_at timestamptz,
  marketing_opt_in boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.md_entitlements enable row level security;

drop policy if exists "md_entitlements_read_own" on public.md_entitlements;
create policy "md_entitlements_read_own" on public.md_entitlements
  for select to authenticated
  using (auth.uid() = user_id);

revoke insert, update, delete on public.md_entitlements from anon, authenticated;
grant select on public.md_entitlements to authenticated;

-- יומן כל אירוע תשלום שהתקבל (לבירור מחלוקות ולהחזרים). שירות בלבד.
create table if not exists public.md_billing_events (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete set null,
  provider text not null,
  event_type text not null,
  provider_ref text,
  amount_agorot integer,
  payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create unique index if not exists md_billing_events_dedupe
  on public.md_billing_events (provider, provider_ref, event_type)
  where provider_ref is not null;
alter table public.md_billing_events enable row level security;
revoke all on public.md_billing_events from anon, authenticated;

-- האם למשתמש יש גישה עכשיו. משמש גם את ה-Workers (מוטי, md-api) דרך RPC.
create or replace function public.md_has_access(uid uuid default auth.uid())
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.md_entitlements e
    where e.user_id = uid
      and e.status in ('active', 'past_due', 'canceled')
      and greatest(
            coalesce(e.trial_ends_at, '-infinity'::timestamptz),
            coalesce(e.current_period_end, '-infinity'::timestamptz)
          ) > now()
  ) or exists (
    select 1 from public.md_entitlements e
    where e.user_id = uid and e.plan in ('founder', 'comp') and e.status = 'active'
      and (e.current_period_end is null or e.current_period_end > now())
  );
$$;
revoke all on function public.md_has_access(uuid) from public;
grant execute on function public.md_has_access(uuid) to authenticated;

-- פתיחת שבוע ניסיון: פעם אחת למשתמש. קריאה חוזרת מחזירה את השורה הקיימת בלי לשנות אותה.
create or replace function public.md_start_trial(accept_terms boolean default false, marketing boolean default false)
returns public.md_entitlements
language plpgsql
security definer
set search_path = public
as $$
declare
  result public.md_entitlements;
begin
  if auth.uid() is null then
    raise exception 'not authenticated' using errcode = '28000';
  end if;
  insert into public.md_entitlements (user_id, plan, status, trial_ends_at, terms_accepted_at, marketing_opt_in)
  values (auth.uid(), 'trial', 'active', now() + interval '7 days',
          case when accept_terms then now() end, marketing)
  on conflict (user_id) do nothing;
  select * into result from public.md_entitlements where user_id = auth.uid();
  return result;
end;
$$;
revoke all on function public.md_start_trial(boolean, boolean) from public;
grant execute on function public.md_start_trial(boolean, boolean) to authenticated;

create or replace function public.md_touch_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;
drop trigger if exists md_entitlements_touch on public.md_entitlements;
create trigger md_entitlements_touch before update on public.md_entitlements
  for each row execute function public.md_touch_updated_at();
