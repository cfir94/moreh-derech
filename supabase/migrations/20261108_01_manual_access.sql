-- 7. משתמש שנרשם עם מייל שהופעל לו מנוי מראש: המנוי מופעל ברגע ההרשמה.
create or replace function public.md_claim_pending_grant()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  g public.md_pending_grants;
begin
  -- הטבלה auth.users משותפת למשחק: תקלה כאן לעולם לא חוסמת הרשמה.
  begin
    select * into g from public.md_pending_grants where email = lower(new.email);
    if found then
      perform public.md_apply_grant(new.id, g.plan, g.months);
      delete from public.md_pending_grants where email = g.email;
    end if;
  exception when others then
    raise warning 'md_claim_pending_grant: %', sqlerrm;
  end;
  return new;
end;
$$;
drop trigger if exists md_claim_pending_grant on auth.users;
create trigger md_claim_pending_grant after insert on auth.users
  for each row execute function public.md_claim_pending_grant();

-- 8. לתזכורות (cron ב-Worker, עם service_role): מנויים שמסתיימים בעוד `days` ימים בערך.
create or replace function public.md_expiring(days integer default 30)
returns table (user_id uuid, email text, full_name text, plan text, current_period_end timestamptz)
language sql
stable
security definer
set search_path = public
as $$
  select u.id, u.email::text, coalesce(p.full_name, ''), e.plan, e.current_period_end
    from public.md_entitlements e
    join auth.users u on u.id = e.user_id
    left join public.md_profiles p on p.user_id = u.id
   where e.status = 'active'
     and e.plan in ('halfyear', 'yearly')
     and e.current_period_end::date = (now() + make_interval(days => days))::date;
$$;
revoke all on function public.md_expiring(integer) from public, anon, authenticated;
grant execute on function public.md_expiring(integer) to service_role;

