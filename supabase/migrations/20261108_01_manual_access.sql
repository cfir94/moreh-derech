  check (plan in ('trial', 'monthly', 'halfyear', 'yearly', 'founder', 'comp'));

-- 2. מחזורים: בית ספר, שנה ושם. כולם קוראים (לבחירה בהרשמה), רק מנהל כותב.
create table if not exists public.md_cohorts (
  id bigint generated by default as identity primary key,
  school text not null,
  year integer not null check (year between 2000 and 2100),
  name text not null,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  unique (school, year, name)
);
alter table public.md_cohorts enable row level security;
drop policy if exists "md_cohorts_read" on public.md_cohorts;
create policy "md_cohorts_read" on public.md_cohorts for select to anon, authenticated using (true);
drop policy if exists "md_cohorts_admin_write" on public.md_cohorts;
create policy "md_cohorts_admin_write" on public.md_cohorts for all to authenticated
  using (public.is_app_admin()) with check (public.is_app_admin());
grant select on public.md_cohorts to anon, authenticated;
grant insert, update, delete on public.md_cohorts to authenticated;

-- 3. פרופיל: שם מלא, טלפון ומחזור. המשתמש קורא וכותב רק את שלו.
create table if not exists public.md_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '' check (char_length(full_name) <= 120),
  phone text not null default '' check (char_length(phone) <= 32),
  cohort_id bigint references public.md_cohorts(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.md_profiles enable row level security;
drop policy if exists "md_profiles_own" on public.md_profiles;
create policy "md_profiles_own" on public.md_profiles for all to authenticated
  using (auth.uid() = user_id) with check (auth.uid() = user_id);
revoke all on public.md_profiles from anon;
grant select, insert, update on public.md_profiles to authenticated;
drop trigger if exists md_profiles_touch on public.md_profiles;
create trigger md_profiles_touch before update on public.md_profiles
  for each row execute function public.md_touch_updated_at();

-- 4. פניות: הרשמה חדשה ("signup") ובקשת מנוי ("join"). משתמש מוסיף רק בשמו; רק מנהל קורא.
create table if not exists public.md_leads (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete set null default auth.uid(),
  kind text not null check (kind in ('signup', 'join')),
  plan text check (plan in ('halfyear', 'yearly')),
  email text not null default '' check (char_length(email) <= 254),
  full_name text not null default '' check (char_length(full_name) <= 120),
  phone text not null default '' check (char_length(phone) <= 32),
  note text not null default '' check (char_length(note) <= 1000),
  handled boolean not null default false,
  created_at timestamptz not null default now()
);
alter table public.md_leads enable row level security;
drop policy if exists "md_leads_insert_own" on public.md_leads;
create policy "md_leads_insert_own" on public.md_leads for insert to authenticated
  with check (auth.uid() = user_id and handled = false);
revoke all on public.md_leads from anon;
grant insert on public.md_leads to authenticated;

-- 5. מנויים שהופעלו למייל שעוד לא נרשם.
create table if not exists public.md_pending_grants (
  email text primary key,
  plan text not null check (plan in ('halfyear', 'yearly', 'comp')),
  months integer not null check (months between 1 and 36),
  created_at timestamptz not null default now()
);
alter table public.md_pending_grants enable row level security;
revoke all on public.md_pending_grants from anon, authenticated;

-- הפעלה בפועל: מאריכה מסוף התקופה הקיימת אם היא עוד בתוקף, אחרת מהיום.
create or replace function public.md_apply_grant(uid uuid, p_plan text, p_months integer)
returns public.md_entitlements
language plpgsql
security definer
set search_path = public
as $$
declare
  result public.md_entitlements;
begin
  insert into public.md_entitlements (user_id, plan, status, current_period_end, provider)
  values (uid, p_plan, 'active', now() + make_interval(months => p_months), 'manual')
  on conflict (user_id) do update set
    plan = excluded.plan,
    status = 'active',
    cancel_at_period_end = false,
    provider = 'manual',
    current_period_end = greatest(coalesce(md_entitlements.current_period_end, now()), now())
                         + make_interval(months => p_months);
  select * into result from public.md_entitlements where user_id = uid;
  return result;
end;
$$;
revoke all on function public.md_apply_grant(uuid, text, integer) from public, anon, authenticated;

-- 6. פעולות מנהל. כל אחת בודקת is_app_admin() בעצמה.
create or replace function public.md_admin_grant(p_email text, p_plan text, p_months integer)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  uid uuid;
  clean text := lower(trim(p_email));
begin
  if not public.is_app_admin() then
    raise exception 'admins only' using errcode = '42501';
  end if;
  if p_plan not in ('halfyear', 'yearly', 'comp') then
    raise exception 'bad plan' using errcode = '22023';
  end if;
  select id into uid from auth.users where lower(email) = clean;
  if uid is null then
    insert into public.md_pending_grants (email, plan, months) values (clean, p_plan, p_months)
    on conflict (email) do update set plan = excluded.plan, months = excluded.months, created_at = now();
    return 'pending';
  end if;
  perform public.md_apply_grant(uid, p_plan, p_months);
  return 'active';
end;
$$;
revoke all on function public.md_admin_grant(text, text, integer) from public, anon;
grant execute on function public.md_admin_grant(text, text, integer) to authenticated;

-- ביטול/סיום מנוי ידני (למשל החזר כספי).
create or replace function public.md_admin_end_access(p_user uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.is_app_admin() then
    raise exception 'admins only' using errcode = '42501';
  end if;
  update public.md_entitlements
     set status = 'expired', current_period_end = now(), trial_ends_at = least(coalesce(trial_ends_at, now()), now())
   where user_id = p_user;
end;
$$;
revoke all on function public.md_admin_end_access(uuid) from public, anon;
grant execute on function public.md_admin_end_access(uuid) to authenticated;

-- כל המשתמשים, עם פרופיל, מחזור ומצב גישה.
create or replace function public.md_admin_users()
returns table (
  user_id uuid, email text, signed_up timestamptz, last_sign_in timestamptz,
  full_name text, phone text, cohort text,
  plan text, status text, trial_ends_at timestamptz, current_period_end timestamptz, has_access boolean
)
language plpgsql
stable
security definer
set search_path = public
as $$
begin
  if not public.is_app_admin() then
    raise exception 'admins only' using errcode = '42501';
  end if;
  return query
    select u.id, u.email::text, u.created_at, u.last_sign_in_at,
           coalesce(p.full_name, u.raw_user_meta_data->>'display_name', ''),
           coalesce(p.phone, ''),
           case when c.id is null then '' else c.school || ' · ' || c.year || ' · ' || c.name end,
           e.plan, e.status, e.trial_ends_at, e.current_period_end,
           public.md_has_access(u.id)
      from auth.users u
      left join public.md_profiles p on p.user_id = u.id
      left join public.md_cohorts c on c.id = p.cohort_id
      left join public.md_entitlements e on e.user_id = u.id
     order by u.created_at desc;
end;
$$;
revoke all on function public.md_admin_users() from public, anon;
grant execute on function public.md_admin_users() to authenticated;

