-- C-10..C-12: קהילה. פורום פרטי למחזור, לוח פרסומים, ומונה הודעות שלא נקראו.
-- החלטות הבעלים (10.11): הודעות מופיעות מיד, והפיקוח בדיעבד (מנהל מסתיר או חוסם).
-- עקרונות:
--   * קורא רק מי שחבר בפורום: חבר פעיל, חבר אוטומטי (מחזור או נרשם לפני תאריך), או מנהל.
--   * כותב רק חבר שלא נחסם, ובשמו בלבד. שם הכותב נשמר בשורה (author_name) בזמן הכתיבה,
--     כדי שלא צריך לחשוף את טבלת הפרופילים.
--   * בלוח פרסומים (kind = 'board') פותח נושא רק מנהל או מי שקיבל role = 'poster'.
--   * מנהל (is_app_admin) רואה הכול ומסתיר/מצמיד/חוסם דרך פונקציות md_admin_forum_*.
--   * הקידומת md_ מפרידה מטבלאות המשחק "אבן דרך", שחולק את אותו פרויקט Supabase.
-- להרצה: Supabase ← SQL Editor ← Run. אידמפוטנטי. דורש 20261106_01 ו-20261108_01.

create table if not exists public.md_forums (
  id bigint generated by default as identity primary key,
  slug text not null unique check (slug ~ '^[a-z0-9-]{2,40}$'),
  title text not null check (char_length(title) between 2 and 80),
  description text not null default '' check (char_length(description) <= 300),
  kind text not null default 'forum' check (kind in ('forum', 'board')),
  -- חברים אוטומטיים: כל מי שבחר את המחזור הזה, ו/או כל מי שנרשם לפני התאריך.
  cohort_id bigint references public.md_cohorts(id) on delete set null,
  auto_before timestamptz,
  -- פתוח לכל משתמש מחובר (לוח הפרסומים הכללי).
  open_to_all boolean not null default false,
  sort integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.md_forum_members (
  forum_id bigint not null references public.md_forums(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  status text not null default 'pending' check (status in ('pending', 'active', 'banned')),
  role text not null default 'member' check (role in ('member', 'poster')),
  created_at timestamptz not null default now(),
  primary key (forum_id, user_id)
);

create table if not exists public.md_threads (
  id bigint generated by default as identity primary key,
  forum_id bigint not null references public.md_forums(id) on delete cascade,
  author_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  author_name text not null default '',
  title text not null check (char_length(title) between 3 and 140),
  body text not null check (char_length(body) between 1 and 8000),
  pinned boolean not null default false,
  hidden boolean not null default false,
  post_count integer not null default 0,
  last_post_at timestamptz not null default now(),
  created_at timestamptz not null default now()
);
create index if not exists md_threads_forum_recent on public.md_threads (forum_id, pinned desc, last_post_at desc);

create table if not exists public.md_posts (
  id bigint generated by default as identity primary key,
  thread_id bigint not null references public.md_threads(id) on delete cascade,
  author_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  author_name text not null default '',
  body text not null check (char_length(body) between 1 and 8000),
  hidden boolean not null default false,
  created_at timestamptz not null default now()
);
create index if not exists md_posts_thread on public.md_posts (thread_id, created_at);

create table if not exists public.md_forum_reads (
  user_id uuid not null references auth.users(id) on delete cascade,
  forum_id bigint not null references public.md_forums(id) on delete cascade,
  last_read_at timestamptz not null default now(),
  primary key (user_id, forum_id)
);

-- מי חבר בפורום. security definer: קורא auth.users ו-md_profiles בשביל החברות האוטומטית.
create or replace function public.md_forum_member(f bigint, uid uuid default auth.uid())
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select uid is not null and (
    public.is_app_admin(uid)
    or exists (select 1 from public.md_forum_members m where m.forum_id = f and m.user_id = uid and m.status = 'active')
    or (
      not exists (select 1 from public.md_forum_members m where m.forum_id = f and m.user_id = uid and m.status = 'banned')
      and exists (
        select 1 from public.md_forums fo
        where fo.id = f and (
          fo.open_to_all
          or (fo.cohort_id is not null and exists (select 1 from public.md_profiles p where p.user_id = uid and p.cohort_id = fo.cohort_id))
          or (fo.auto_before is not null and exists (select 1 from auth.users u where u.id = uid and u.created_at < fo.auto_before))
        )
      )
    )
  );
$$;
revoke all on function public.md_forum_member(bigint, uuid) from public;
grant execute on function public.md_forum_member(bigint, uuid) to authenticated;

-- מי רשאי לפתוח נושא: בפורום רגיל כל חבר; בלוח פרסומים רק מנהל או poster.
create or replace function public.md_forum_can_open(f bigint, uid uuid default auth.uid())
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select public.md_forum_member(f, uid) and (
    public.is_app_admin(uid)
    or (select kind from public.md_forums where id = f) = 'forum'
    or exists (select 1 from public.md_forum_members m where m.forum_id = f and m.user_id = uid and m.role = 'poster' and m.status = 'active')
  );
$$;
revoke all on function public.md_forum_can_open(bigint, uuid) from public;
grant execute on function public.md_forum_can_open(bigint, uuid) to authenticated;

-- שם הכותב נכתב בשרת, לא מהדפדפן.
create or replace function public.md_forum_author_name()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  new.author_id := auth.uid();
  select coalesce(nullif(p.full_name, ''), nullif(u.raw_user_meta_data->>'display_name', ''), split_part(u.email, '@', 1))
    into new.author_name
    from auth.users u left join public.md_profiles p on p.user_id = u.id
   where u.id = new.author_id;
  new.hidden := false;
  return new;
end;
$$;

create or replace function public.md_forum_bump_thread()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.md_threads set post_count = post_count + 1, last_post_at = new.created_at where id = new.thread_id;
  return new;
end;
$$;

drop trigger if exists md_threads_author on public.md_threads;
create trigger md_threads_author before insert on public.md_threads
  for each row execute function public.md_forum_author_name();
drop trigger if exists md_posts_author on public.md_posts;
create trigger md_posts_author before insert on public.md_posts
  for each row execute function public.md_forum_author_name();
drop trigger if exists md_posts_bump on public.md_posts;
create trigger md_posts_bump after insert on public.md_posts
  for each row execute function public.md_forum_bump_thread();

-- RLS
alter table public.md_forums enable row level security;
alter table public.md_forum_members enable row level security;
alter table public.md_threads enable row level security;
alter table public.md_posts enable row level security;
alter table public.md_forum_reads enable row level security;

drop policy if exists "md_forums_read" on public.md_forums;
create policy "md_forums_read" on public.md_forums for select to authenticated
  using (true); -- הרשימה עצמה גלויה, כדי שאפשר יהיה לבקש להצטרף; התוכן מוגן בטבלאות האחרות.
drop policy if exists "md_forums_admin" on public.md_forums;
create policy "md_forums_admin" on public.md_forums for all to authenticated
  using (public.is_app_admin()) with check (public.is_app_admin());

drop policy if exists "md_members_own" on public.md_forum_members;
create policy "md_members_own" on public.md_forum_members for select to authenticated
  using (user_id = auth.uid() or public.is_app_admin());
drop policy if exists "md_members_request" on public.md_forum_members;
create policy "md_members_request" on public.md_forum_members for insert to authenticated
  with check (user_id = auth.uid() and status = 'pending' and role = 'member');
drop policy if exists "md_members_admin" on public.md_forum_members;
create policy "md_members_admin" on public.md_forum_members for update to authenticated
  using (public.is_app_admin()) with check (public.is_app_admin());

drop policy if exists "md_threads_read" on public.md_threads;
create policy "md_threads_read" on public.md_threads for select to authenticated
  using (public.md_forum_member(forum_id) and (not hidden or author_id = auth.uid() or public.is_app_admin()));
drop policy if exists "md_threads_write" on public.md_threads;
create policy "md_threads_write" on public.md_threads for insert to authenticated
  with check (public.md_forum_can_open(forum_id));

drop policy if exists "md_posts_read" on public.md_posts;
create policy "md_posts_read" on public.md_posts for select to authenticated
  using (
    exists (select 1 from public.md_threads t where t.id = thread_id and public.md_forum_member(t.forum_id)
            and (not t.hidden or public.is_app_admin()))
    and (not hidden or author_id = auth.uid() or public.is_app_admin())
  );
drop policy if exists "md_posts_write" on public.md_posts;
create policy "md_posts_write" on public.md_posts for insert to authenticated
  with check (exists (select 1 from public.md_threads t where t.id = thread_id and not t.hidden and public.md_forum_member(t.forum_id)));

drop policy if exists "md_reads_own" on public.md_forum_reads;
create policy "md_reads_own" on public.md_forum_reads for all to authenticated
  using (user_id = auth.uid()) with check (user_id = auth.uid());

revoke all on public.md_forums, public.md_forum_members, public.md_threads, public.md_posts, public.md_forum_reads from anon;
grant select on public.md_forums to authenticated;
grant insert, update on public.md_forums to authenticated;
grant select, insert, update on public.md_forum_members to authenticated;
grant select, insert on public.md_threads, public.md_posts to authenticated;
grant select, insert, update on public.md_forum_reads to authenticated;

-- הפורומים שאני רואה, עם מצב החברות שלי ומספר העדכונים שלא קראתי.
create or replace function public.md_my_forums()
returns table (id bigint, slug text, title text, description text, kind text, member boolean, can_open boolean,
               request text, unread integer, last_activity timestamptz)
language sql
stable
security definer
set search_path = public
as $$
  select f.id, f.slug, f.title, f.description, f.kind,
         public.md_forum_member(f.id), public.md_forum_can_open(f.id),
         (select m.status from public.md_forum_members m where m.forum_id = f.id and m.user_id = auth.uid()),
         case when public.md_forum_member(f.id) then (
           (select count(*) from public.md_threads t where t.forum_id = f.id and not t.hidden and t.author_id <> auth.uid()
              and t.created_at > coalesce((select r.last_read_at from public.md_forum_reads r where r.user_id = auth.uid() and r.forum_id = f.id), '-infinity'))
           + (select count(*) from public.md_posts p join public.md_threads t on t.id = p.thread_id
              where t.forum_id = f.id and not p.hidden and not t.hidden and p.author_id <> auth.uid()
                and p.created_at > coalesce((select r.last_read_at from public.md_forum_reads r where r.user_id = auth.uid() and r.forum_id = f.id), '-infinity'))
         )::integer else 0 end,
         (select max(t.last_post_at) from public.md_threads t where t.forum_id = f.id and not t.hidden)
    from public.md_forums f
   where auth.uid() is not null
   order by f.sort, f.id;
$$;
revoke all on function public.md_my_forums() from public;
grant execute on function public.md_my_forums() to authenticated;

-- פעולות מנהל
create or replace function public.md_admin_forum_hide(p_kind text, p_id bigint, p_hidden boolean)
returns void language plpgsql security definer set search_path = public as $$
begin
  if not public.is_app_admin() then raise exception 'admins only' using errcode = '42501'; end if;
  if p_kind = 'thread' then update public.md_threads set hidden = p_hidden where id = p_id;
  elsif p_kind = 'post' then update public.md_posts set hidden = p_hidden where id = p_id;
  else raise exception 'bad kind' using errcode = '22023'; end if;
end; $$;

create or replace function public.md_admin_forum_pin(p_thread bigint, p_pinned boolean)
returns void language plpgsql security definer set search_path = public as $$
begin
  if not public.is_app_admin() then raise exception 'admins only' using errcode = '42501'; end if;
  update public.md_threads set pinned = p_pinned where id = p_thread;
end; $$;

-- אישור בקשה, חסימה או מתן הרשאת פרסום. p_status: active / banned; p_role: member / poster.
create or replace function public.md_admin_forum_member(p_forum bigint, p_user uuid, p_status text, p_role text default 'member')
returns void language plpgsql security definer set search_path = public as $$
begin
  if not public.is_app_admin() then raise exception 'admins only' using errcode = '42501'; end if;
  insert into public.md_forum_members (forum_id, user_id, status, role) values (p_forum, p_user, p_status, p_role)
  on conflict (forum_id, user_id) do update set status = excluded.status, role = excluded.role;
end; $$;

create or replace function public.md_admin_forum_requests()
returns table (forum_id bigint, forum_title text, user_id uuid, email text, full_name text, status text, role text, created_at timestamptz)
language plpgsql stable security definer set search_path = public as $$
begin
  if not public.is_app_admin() then raise exception 'admins only' using errcode = '42501'; end if;
  return query
    select m.forum_id, f.title, m.user_id, u.email::text, coalesce(p.full_name, ''), m.status, m.role, m.created_at
      from public.md_forum_members m
      join public.md_forums f on f.id = m.forum_id
      join auth.users u on u.id = m.user_id
      left join public.md_profiles p on p.user_id = m.user_id
     order by (m.status = 'pending') desc, m.created_at desc;
end; $$;

do $$ begin
  revoke all on function public.md_admin_forum_hide(text, bigint, boolean) from public, anon;
  revoke all on function public.md_admin_forum_pin(bigint, boolean) from public, anon;
  revoke all on function public.md_admin_forum_member(bigint, uuid, text, text) from public, anon;
  revoke all on function public.md_admin_forum_requests() from public, anon;
end $$;
grant execute on function public.md_admin_forum_hide(text, bigint, boolean) to authenticated;
grant execute on function public.md_admin_forum_pin(bigint, boolean) to authenticated;
grant execute on function public.md_admin_forum_member(bigint, uuid, text, text) to authenticated;
grant execute on function public.md_admin_forum_requests() to authenticated;

