export function buildSystemInstruction(c: ServerCharacter): string {
  const guide = c.kind === "guide";
  const parts = [
    guide ? GUIDE_RULES : GENERAL_RULES,
    `הדמות שלך:\n${c.prompt}`,
    `משפט הפתיחה שלך (אמור אותו, או נוסח קרוב מאוד, כשהגולש מצטרף): "${c.openingLineHe}"`,
    guide ? GUIDE_TOOL_INSTRUCTIONS : TOOL_INSTRUCTIONS,
  ];
  if (c.knowledgeSheet) parts.push(`דף הידע שלך (תקציר; לפרטים ולציטוטים — search_sources):\n${c.knowledgeSheet}`);
  return parts.join("\n\n");
}

